float class_weight(CharClass c) {
    switch (c) {
        case CharClass::Cjk:
        case CharClass::Ethiopic:
        case CharClass::Yi:
            return 3.0f;
        case CharClass::Hangul:
            return 2.5f;
        case CharClass::Kana:
            return 2.2f;
        case CharClass::Indic:
        case CharClass::KhmerMyanmar:
            return 1.8f;
        case CharClass::ThaiLao:
        case CharClass::Arabic:
        case CharClass::Hebrew:
            return 1.5f;
        case CharClass::Latin:
        case CharClass::Cyrillic:
        case CharClass::Greek:
        case CharClass::Armenian:
        case CharClass::Georgian:
        case CharClass::Default:
            return 1.0f;
        case CharClass::Punctuation:
            return 0.5f;
        case CharClass::Space:
            return 0.2f;
        case CharClass::Digit:
            return 3.5f;
        case CharClass::Mark:
            return 0.0f;
    }
    return 1.0f;
}

CharClass char_class(char32_t cp) {
    // ASCII letters and the space are the overwhelming majority of what this
    // sees, and both would reach the same answer the long way round.
    if ((cp >= U'A' && cp <= U'Z') || (cp >= U'a' && cp <= U'z')) {
        return CharClass::Latin;
    }
    if (cp == U' ') {
        return CharClass::Space;
    }

    // U+0640 ARABIC TATWEEL is a letter by category but a pure typographic
    // stretch -- it lengthens the join between two letters and is not spoken.
    if (cp == 0x0640) {
        return CharClass::Mark;
    }

    // Category before block, so that a combining mark inside a script block is
    // still free and a full stop inside a CJK run is still a pause.
    const auto cat = std::upper_bound(kCategories.begin(), kCategories.end(), cp,
                                      [](char32_t v, const CatRange& r) { return v < r.lo; });
    if (cat != kCategories.begin() && cp <= std::prev(cat)->hi) {
        return std::prev(cat)->cls;
    }

    const auto block = std::lower_bound(kBlocks.begin(), kBlocks.end(), cp,
                                        [](const Block& b, char32_t v) { return b.end < v; });
    if (block != kBlocks.end()) {
        return block->cls;
    }

    // Past the last block. The supplementary planes above U+20000 are CJK
    // extensions; below that sits everything from Linear B to the emoji that
    // the category pass already claimed.
    return cp > 0x20000 ? CharClass::Cjk : CharClass::Default;
}

double text_weight(std::string_view text) {
    double total = 0.0;
    for (const char32_t cp : utf8::decode(text)) {
        total += static_cast<double>(char_weight(cp));
    }
    return total;
}

// =============================================================================
// Estimation
// =============================================================================

double estimate_duration(std::string_view target, std::string_view ref, double ref_duration,
                         double low_threshold, double boost_strength) {
    if (ref_duration <= 0.0 || ref.empty()) {
        return 0.0;
    }
    const double ref_weight = text_weight(ref);
    if (ref_weight <= 0.0) {
        return 0.0;
    }

    // Weight per unit of time, measured on the reference phrase.
    const double speed = ref_weight / ref_duration;
    const double estimate = text_weight(target) / speed;

    if (low_threshold > 0.0 && estimate < low_threshold) {
        const double alpha = 1.0 / boost_strength;
        return low_threshold * std::pow(estimate / low_threshold, alpha);
    }
    return estimate;
}

